-- 部屋マスタ
CREATE TABLE `Rooms` (
  `RoomId` int NOT NULL AUTO_INCREMENT,
  `PropertyId` int NOT NULL,
  `RoomNo` varchar(20) NOT NULL,
  `RoomName` varchar(100) DEFAULT NULL,
  `Capacity` int DEFAULT 1,
  `Status` int DEFAULT 1,
  PRIMARY KEY (`RoomId`)
);
-- 外部キー追加
ALTER TABLE `Rooms`
ADD CONSTRAINT `FK_Rooms_Properties`
FOREIGN KEY (`PropertyId`)
REFERENCES `Properties` (`PropertyId`);

-- 予約テーブル
CREATE TABLE RESERVATIONS (
    RESERVATION_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    ROOM_ID NUMBER,
    CHECKIN_DATE DATE,
    CHECKOUT_DATE DATE,
    CUSTOMER_NAME VARCHAR2(100)
);
-- 空室カレンダーテーブル
CREATE TABLE ROOM_CALENDAR (
    CALENDAR_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    ROOM_ID NUMBER NOT NULL,
    TARGET_DATE DATE NOT NULL,
    STATUS NUMBER DEFAULT 0,

    CONSTRAINT PK_ROOM_CALENDAR PRIMARY KEY(CALENDAR_ID)
);
/* STATUS:
0 = 空室
1 = 予約済
2 = 清掃中
3 = メンテナンス
*/

